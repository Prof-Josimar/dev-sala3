package view;

public class IncDec {


    public static void main(String[] args) {

        int x = 5;
        int y = 4;
        y++;
        // mostro e incremento
        System.out.println(++x);

        // incremento e mostro
        System.out.println(x++);

        System.out.println(x+y);




    }


}




