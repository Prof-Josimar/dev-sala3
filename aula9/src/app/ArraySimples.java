package app;

public class ArraySimples {
    public static void main(String[] args) {
        final int TAM = 3;

        String[] nome = new String[TAM];

        nome[0] = "Ana";
        nome[1] = "Bia";
        nome[2] = "Lia";

        System.out.println(nome[0]);
        System.out.println(nome[1]);
        System.out.println(nome[2]);

    }
}
