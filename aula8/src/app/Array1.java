package app;

public class Array1 {

    public static void main(String[] args) {
        String[] nome = new String[5];
        nome[0] = "Ana";
        nome[1] = "Bia";
        nome[2] = "Carla";
        nome[3] = "Eva";
        nome[4] = "Fabiana";

        for (int i = 0; i < nome.length; i++) {
            System.out.println(nome[i]);
        }


    }

}
